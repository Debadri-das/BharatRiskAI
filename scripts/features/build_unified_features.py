"""Build unified 13-channel feature grids from satellite, atmospheric, and DEM sources.

Consumes:
- Preprocessed INSAT satellite features (CTT, CTT cooling rate, WV radiance)
- Standardized INSAT QPE products (instantaneous rate and validity mask; NaNs preserved)
- Timestamped atmospheric products from scripts/atmosphere/derive_features.py (*.nc)
- Hydrologically conditioned DEM terrain features including measured drainage
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import rasterio
from rasterio.enums import Resampling
from rasterio.transform import from_bounds
from rasterio.warp import reproject
import xarray as xr

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from reports.unified_feature_schema import CHANNEL_ORDER

TARGET_SHAPE = (114, 84)
TARGET_BOUNDS = (85.7, 21.5, 89.9, 27.2)  # west, south, east, north


def _parse_timestamp(val: Any) -> datetime:
    if isinstance(val, np.datetime64):
        val = val.astype("datetime64[us]").astype(datetime)
    if isinstance(val, datetime):
        return val if val.tzinfo else val.replace(tzinfo=timezone.utc)
    text = str(val).replace("Z", "+00:00")
    try:
        dt = datetime.fromisoformat(text)
        return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    except ValueError:
        # Regex fallback for YYYYMMDD_HHMM or YYYYMMDDTHHMMSS
        m = re.search(r"(\d{4})(\d{2})(\d{2})[T_](\d{2})(\d{2})", text)
        if m:
            return datetime(int(m.group(1)), int(m.group(2)), int(m.group(3)),
                            int(m.group(4)), int(m.group(5)), tzinfo=timezone.utc)
        raise ValueError(f"Cannot parse timestamp from {val!r}")


def _align_to_target_grid(
    values: np.ndarray,
    latitudes: np.ndarray,
    longitudes: np.ndarray,
) -> np.ndarray:
    """Reproject 2D atmospheric grid to target EPSG:4326 (114, 84) domain."""
    values_2d = np.asarray(values, dtype=np.float32).squeeze()
    if values_2d.shape == TARGET_SHAPE:
        return values_2d

    lat_flat = np.asarray(latitudes).ravel()
    lon_flat = np.asarray(longitudes).ravel()
    valid_lats = lat_flat[np.isfinite(lat_flat)]
    valid_lons = lon_flat[np.isfinite(lon_flat)]
    if valid_lats.size == 0 or valid_lons.size == 0:
        return np.full(TARGET_SHAPE, np.nan, dtype=np.float32)

    src_transform = from_bounds(
        float(np.min(valid_lons)),
        float(np.min(valid_lats)),
        float(np.max(valid_lons)),
        float(np.max(valid_lats)),
        values_2d.shape[1],
        values_2d.shape[0],
    )
    dst_transform = from_bounds(
        TARGET_BOUNDS[0], TARGET_BOUNDS[1], TARGET_BOUNDS[2], TARGET_BOUNDS[3],
        TARGET_SHAPE[1], TARGET_SHAPE[0],
    )
    output = np.full(TARGET_SHAPE, np.nan, dtype=np.float32)
    reproject(
        values_2d,
        output,
        src_transform=src_transform,
        src_crs="EPSG:4326",
        dst_transform=dst_transform,
        dst_crs="EPSG:4326",
        src_nodata=np.nan,
        dst_nodata=np.nan,
        resampling=Resampling.bilinear,
    )
    return output


def load_atmospheric_products() -> dict[datetime, dict[str, np.ndarray]]:
    """Discover and index NetCDF products generated by derive_features.py."""
    candidates = [
        ROOT / "data" / "processed" / "atmospheric_features",
        ROOT / "data" / "derived" / "atmosphere",
    ]
    nc_paths: list[Path] = []
    for directory in candidates:
        if directory.exists():
            nc_paths.extend(sorted(directory.glob("*.nc*")))
            
    npz_paths: list[Path] = []
    for directory in candidates:
        if directory.exists():
            npz_paths.extend(sorted(directory.glob("*.npz")))

    lookup: dict[datetime, dict[str, np.ndarray]] = {}

    for path in nc_paths:
        try:
            with xr.open_dataset(path, engine="h5netcdf") as ds:
                # Determine timestamp from metadata or coords
                ts_raw = ds.attrs.get("source_valid_time")
                if ts_raw is None:
                    for name in ("valid_time", "time", "forecast_time"):
                        if name in ds.coords:
                            ts_raw = ds[name].values.reshape(-1)[0]
                            break
                if ts_raw is None:
                    ts_raw = path.stem
                stamp = _parse_timestamp(ts_raw)

                lat_coord = next((ds[c].values for c in ("latitude", "lat") if c in ds.coords), None)
                lon_coord = next((ds[c].values for c in ("longitude", "lon") if c in ds.coords), None)

                # Extract required physical quantities
                # Map variable aliases from derive_features.py
                iwv = ds["iwv"].values if "iwv" in ds else None
                cape = ds["cape"].values if "cape" in ds else None
                cin = ds["cin"].values if "cin" in ds else None
                
                conv_var = next((v for v in ("horizontal_convergence", "convergence") if v in ds), None)
                convergence = ds[conv_var].values if conv_var else None

                shear_var = next((v for v in ("wind_shear_0_6km", "wind_shear") if v in ds), None)
                wind_shear = ds[shear_var].values if shear_var else None

                rain_var = next((v for v in ("surface_rainfall", "total_precipitation", "rainfall", "tp") if v in ds), None)
                rainfall = ds[rain_var].values if rain_var else None

                if iwv is None or cape is None or cin is None or convergence is None or wind_shear is None:
                    continue

                if lat_coord is not None and lon_coord is not None:
                    aligned = {
                        "iwv": _align_to_target_grid(iwv, lat_coord, lon_coord),
                        "cape": _align_to_target_grid(cape, lat_coord, lon_coord),
                        "cin": _align_to_target_grid(cin, lat_coord, lon_coord),
                        "convergence": _align_to_target_grid(convergence, lat_coord, lon_coord),
                        "wind_shear": _align_to_target_grid(wind_shear, lat_coord, lon_coord),
                    }
                    if rainfall is not None:
                        aligned["rainfall"] = _align_to_target_grid(rainfall, lat_coord, lon_coord)
                    lookup[stamp] = aligned
        except Exception:
            continue

    # Fallback to .npz products if available
    for path in npz_paths:
        try:
            with np.load(path, allow_pickle=False) as data:
                if "timestamp" not in data:
                    continue
                stamp = _parse_timestamp(data["timestamp"])
                if stamp in lookup:
                    continue
                required = ("iwv", "cape", "cin", "convergence", "wind_shear")
                if all(name in data for name in required):
                    lookup[stamp] = {name: data[name].astype(np.float32) for name in required}
        except Exception:
            continue

    return lookup


def build_unified_features(output_dir: Path | None = None) -> None:
    dem_path = ROOT / "data" / "derived" / "terrain" / "dem_features.npz"
    if not dem_path.exists():
        raise FileNotFoundError(f"DEM features not found at {dem_path}. Run scripts/features/dem_features.py first.")
    
    dem_data = np.load(dem_path)
    elevation = dem_data["elevation"].astype(np.float32)
    slope = dem_data["slope"].astype(np.float32)
    if "drainage" in dem_data:
        drainage = dem_data["drainage"].astype(np.float32)
    else:
        raise RuntimeError("DEM features file does not contain a measured drainage channel. Run scripts/features/dem_features.py.")
        
    terrain_metadata = dem_path.with_suffix(".json")
    if terrain_metadata.exists():
        meta_text = terrain_metadata.read_text(encoding="utf-8")
        if '"status": "unavailable"' in meta_text:
            raise RuntimeError("Unified feature construction requires a supplied hydrological drainage product; slope is not drainage.")

    sat_files = sorted(ROOT.glob("data/derived/satellite/[0-9]*.npz"))
    if not sat_files:
        raise FileNotFoundError("No satellite feature files found in data/derived/satellite")

    # Load atmospheric feature products from derive_features.py
    atmosphere_lookup = load_atmospheric_products()
    if not atmosphere_lookup:
        raise RuntimeError(
            "No derived atmospheric NetCDF products found in data/processed/atmospheric_features. "
            "Run python -m scripts.atmosphere.derive_features first; no fallback values or hardcoded profiles are permitted."
        )

    # Load QPE lookup preserving NaNs and validity masks
    qpe_files = sorted(ROOT.glob("data/derived/satellite/qpe_*.npz"))
    qpe_lookup: dict[datetime, dict[str, np.ndarray]] = {}
    for qf in qpe_files:
        with np.load(qf) as qd:
            q_ts = _parse_timestamp(qd["timestamp"])
            rate = qd["qpe_rate_mm_hr"].astype(np.float32)
            mask = qd["qpe_valid_mask"] if "qpe_valid_mask" in qd else np.isfinite(rate)
            qpe_lookup[q_ts] = {"rate": rate, "mask": mask}

    if output_dir is None:
        output_dir = ROOT / "data" / "derived" / "unified"
    output_dir.mkdir(parents=True, exist_ok=True)

    previous_iwv = None

    print(f"Building unified 13-channel grids across {len(sat_files)} satellite scenes...")
    count_written = 0
    for idx, sat_path in enumerate(sat_files, 1):
        stem = sat_path.stem
        target_file = output_dir / f"{stem}.npz"
        if target_file.exists() and target_file.stat().st_size > 10000:
            continue
        with np.load(sat_path) as sat_data:
            ts_str = str(sat_data["timestamp"])
            ts = _parse_timestamp(ts_str)
            stem = sat_path.stem

            ctt = sat_data["tir1_bt_c"].astype(np.float32)
            ctt_drop_rate = sat_data["ctt_cooling_rate"].astype(np.float32)

            # Match QPE with NaN preservation
            matched_qpe = None
            if ts in qpe_lookup:
                matched_qpe = qpe_lookup[ts]
            else:
                best_diff = 1800.0  # within 30 minutes
                for q_time, q_obj in qpe_lookup.items():
                    diff = abs((ts - q_time).total_seconds())
                    if diff < best_diff:
                        best_diff = diff
                        matched_qpe = q_obj

            if matched_qpe is not None:
                qpe = matched_qpe["rate"]
                qpe_valid_mask = matched_qpe["mask"]
            else:
                qpe = np.full(TARGET_SHAPE, np.nan, dtype=np.float32)
                qpe_valid_mask = np.zeros(TARGET_SHAPE, dtype=bool)

            # Match Atmospheric products (within 1.5h to cover 3-hourly reanalysis cadence)
            matched_atm = None
            if ts in atmosphere_lookup:
                matched_atm = atmosphere_lookup[ts]
            else:
                best_diff = 5400.0  # within 1.5 hours (90 minutes)
                for a_time, a_obj in atmosphere_lookup.items():
                    diff = abs((ts - a_time).total_seconds())
                    if diff <= best_diff:
                        best_diff = diff
                        matched_atm = a_obj

            if matched_atm is None:
                # Skip satellite passes that do not have contemporaneous atmospheric reanalysis
                continue

            iwv = matched_atm["iwv"].astype(np.float32)
            cape = matched_atm["cape"].astype(np.float32)
            cin = matched_atm["cin"].astype(np.float32)
            convergence = matched_atm["convergence"].astype(np.float32)
            wind_shear = matched_atm["wind_shear"].astype(np.float32)

            if previous_iwv is not None:
                iwv_change = (iwv - previous_iwv).astype(np.float32)
            else:
                iwv_change = np.full_like(iwv, np.nan)
            previous_iwv = iwv

            # Surface rainfall: use atmospheric reanalysis surface rainfall if present, else QPE
            if "rainfall" in matched_atm:
                rainfall = matched_atm["rainfall"].astype(np.float32)
            else:
                rainfall = qpe.copy()

            channels = {
                "iwv": iwv,
                "iwv_change": iwv_change,
                "ctt": ctt,
                "ctt_drop_rate": ctt_drop_rate,
                "qpe": qpe,
                "rainfall": rainfall,
                "cape": cape,
                "cin": cin,
                "convergence": convergence,
                "wind_shear": wind_shear,
                "elevation": elevation,
                "slope": slope,
                "drainage": drainage,
            }

            # Verify all canonical channels are present and correctly shaped
            for ch in CHANNEL_ORDER:
                assert ch in channels, f"Missing channel {ch}"
                assert channels[ch].shape == TARGET_SHAPE, f"Bad shape for {ch}: {channels[ch].shape}"

            target_file = output_dir / f"{stem}.npz"
            np.savez_compressed(
                target_file,
                timestamp=ts.isoformat(),
                qpe_valid_mask=qpe_valid_mask,
                **channels,
            )
            count_written += 1
            if count_written % 100 == 0:
                print(f"  Generated {count_written} new unified grids...")

    print(f"Successfully generated {count_written} new unified 13-channel grids in {output_dir}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Build unified 13-channel feature grids")
    parser.add_argument("--output", type=Path, default=ROOT / "data" / "derived" / "unified")
    args = parser.parse_args()
    build_unified_features(args.output)


if __name__ == "__main__":
    main()
