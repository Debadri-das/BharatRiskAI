create policy risk_assessments_backend_insert on risk_assessments for insert to anon, authenticated with check (true);
drop policy if exists reports_public_read on citizen_reports;
create policy reports_public_read on citizen_reports for select to anon, authenticated using (true);
drop policy if exists reports_public_insert on citizen_reports;
create policy reports_public_insert on citizen_reports for insert to anon, authenticated with check (true);
drop policy if exists emergencies_public_read on emergencies;
create policy emergencies_public_read on emergencies for select to anon, authenticated using (true);
drop policy if exists emergencies_public_insert on emergencies;
create policy emergencies_public_insert on emergencies for insert to anon, authenticated with check (true);